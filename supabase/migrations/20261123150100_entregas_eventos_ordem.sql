-- =====================================================================
-- Módulo de Entregas · renumera entrega_evento.seq dos eventos já existentes · 2026-11-23
-- ---------------------------------------------------------------------
-- A coluna seq (20261123150000) numerou as linhas antigas na ordem física da tabela.
-- Aqui a ordem passa a ser a hora do evento e, no mesmo instante, a ordem lógica em que as
-- RPCs gravam (ação da parada antes da conclusão; estorno antes da reabertura).
-- Eventos novos já nascem em ordem (seq é IDENTITY). Só dados; não muda estrutura.
-- =====================================================================
ALTER TABLE public.entrega_evento DISABLE TRIGGER trg_entrega_evento_imutavel;
ALTER TABLE public.entrega_evento ALTER COLUMN seq SET GENERATED BY DEFAULT;

WITH ordem AS (
  SELECT id, row_number() OVER (ORDER BY ocorrido_em, CASE tipo
    WHEN 'ATRIBUIDA' THEN 1 WHEN 'REATRIBUIDA' THEN 2 WHEN 'ACEITA' THEN 3
    WHEN 'OCORRENCIA' THEN 4 WHEN 'PARADA_ENTREGUE' THEN 5 WHEN 'PARADA_ESTORNADA' THEN 6
    WHEN 'REABERTA' THEN 7 WHEN 'CONCLUIDA' THEN 8 WHEN 'CANCELADA' THEN 9 ELSE 10 END, seq) AS n
  FROM public.entrega_evento
)
UPDATE public.entrega_evento ev SET seq = ordem.n FROM ordem WHERE ordem.id = ev.id;

SELECT setval(pg_get_serial_sequence('public.entrega_evento', 'seq'), COALESCE((SELECT max(seq) FROM public.entrega_evento), 0) + 1, false);
ALTER TABLE public.entrega_evento ALTER COLUMN seq SET GENERATED ALWAYS;
ALTER TABLE public.entrega_evento ENABLE TRIGGER trg_entrega_evento_imutavel;
